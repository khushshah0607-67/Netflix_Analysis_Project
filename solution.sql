-- TAG 'BAD' IF KEYWORDS LIKE 'KILL' AND 'VIOLENCE' ARE PRESENT ELSE TAG GOOD. AND COUNT NUMBER OF GOOD AND BAD CONTENTS
WITH CONTENT_CATEGORY
AS
(
	SELECT 
		DESCRIPTION,
		CASE
			WHEN DESCRIPTION LIKE '%Kill%' OR DESCRIPTION LIKE '%Violence%' THEN 'Bad'
			ELSE 'Good'
		END category
	FROM NET
)
SELECT category, COUNT(*)
FROM CONTENT_CATEGORY
GROUP BY 1;