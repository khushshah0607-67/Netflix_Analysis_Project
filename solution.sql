-- CONTENT ADDED IN LAST 5 YEARS
SELECT *
FROM NET
WHERE current_date() - STR_TO_DATE(DATE_ADDED, '%M %d, %Y') >5;

-- ALL MOVIES/SHOWS BY DIRECTOR 'RAJIV CHILAKA'
SELECT *
FROM NET
WHERE DIRECTOR LIKE '%Rajiv Chilaka%';

-- ALL TV SHOWS WITH MORE THAN 5 SEASONS
SELECT *
FROM NET
WHERE TYPE = 'TV Show' AND CAST(SUBSTR(DURATION, 1, 2) AS UNSIGNED) > 5;

-- HIGHEST AVERAGE RELEASE PER YEAR BY INDIA
SELECT 
	EXTRACT(YEAR FROM STR_TO_DATE(DATE_ADDED, "%M %d, %Y")) AS YEAR,
    COUNT(*) AS COUNT,
    COUNT(*)/(SELECT COUNT(*) FROM NET WHERE COUNTRY = 'India') * 100 AS AVG_CONTENT_PER_YEAR
FROM NET
WHERE COUNTRY = 'India'
GROUP BY 1
ORDER BY 3 DESC;

