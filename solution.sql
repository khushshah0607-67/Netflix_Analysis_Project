-- COUNT NUMBER OF MOVIES AND TV SHOWS --
SELECT TYPE, COUNT(*) AS TOTAL
FROM NET
GROUP BY TYPE;

-- MOST COMMON RATING FOR MOVIES AND TV SHOWS
SELECT TYPE, RATING
FROM 
(
	SELECT 
		TYPE, 
		RATING, 
		COUNT(*),
		RANK() OVER(PARTITION BY TYPE ORDER BY COUNT(*) DESC) AS RANKING
	FROM NET 
	GROUP BY 1, 2
) AS T1
WHERE RANKING = 1;

-- ALL MOVIES RELEASED IN YEAR 2020
SELECT *
FROM NET
WHERE 
	TYPE = 'Movie' 
    AND 
    RELEASE_YEAR = 2020;
    
-- TOP 5 COUNTRIES WITH MOST CONTENT ON NETFLIX
SELECT COUNTRY, COUNT(*)
FROM NET
GROUP BY COUNTRY
ORDER BY 2 DESC
LIMIT 6;

-- LONGEST MOVIE
SELECT type, MAX(CAST(SUBSTR(DURATION, 1, 3) AS UNSIGNED))
